"""Stable, machine-readable reason codes for the Prediction Contract v1.0.0.

Five separate families; no value appears in more than one family (tested), so a code always says where it came from:
  ModelReasonCode          why the model/decision policy produced its direction (part of the prediction)
  ValidationFailureCode    why a prediction payload is structurally invalid (raised, never stored as state)
  DataQualityCode          why the inputs fail point-in-time / freshness rules (raised, never stored as state)
  ExpiryReasonCode / InvalidationReasonCode   why a once-valid prediction is no longer valid (state records)
  RiskRejectionCode        why the Risk Engine rejected a prediction (risk assessments only)
Free-form text may accompany codes (Prediction.explanation, RiskAssessment.notes) but never replaces them.
"""
from __future__ import annotations

from enum import Enum


class ModelReasonCode(str, Enum):
    DIRECTIONAL_EDGE = "MODEL_DIRECTIONAL_EDGE"                      # the only reason allowed with LONG/SHORT
    NO_TRADE_LOW_EDGE = "MODEL_NO_TRADE_LOW_EDGE"
    NO_TRADE_PROBABILITY_BELOW_THRESHOLD = "MODEL_NO_TRADE_PROBABILITY_BELOW_THRESHOLD"
    NO_TRADE_NET_R_BELOW_MINIMUM = "MODEL_NO_TRADE_NET_R_BELOW_MINIMUM"
    NO_TRADE_NET_R_UNAVAILABLE = "MODEL_NO_TRADE_NET_R_UNAVAILABLE"
    NO_TRADE_UNCERTAINTY_TOO_HIGH = "MODEL_NO_TRADE_UNCERTAINTY_TOO_HIGH"
    NO_TRADE_UNCALIBRATED = "MODEL_NO_TRADE_UNCALIBRATED"
    NO_TRADE_CONFLICTING_SIGNALS = "MODEL_NO_TRADE_CONFLICTING_SIGNALS"
    NO_TRADE_MODEL_ABSTAINED = "MODEL_NO_TRADE_MODEL_ABSTAINED"


NO_TRADE_MODEL_REASONS = frozenset(c for c in ModelReasonCode if c is not ModelReasonCode.DIRECTIONAL_EDGE)


